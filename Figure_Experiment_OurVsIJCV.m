%% 对比计算时间
clc; clear; close all;
%%
IJCVSlow = load("Data\Data_ExperimentPlaneIJCVDataset_EfficiencySlow.mat");
PPASlow = load("Data\Data_ExperimentPlanePPADataset_EfficiencySlow.mat");
PPASlow.time_ours = PPASlow.time_ours*1e6;
PPASlow.time_IJCV = PPASlow.time_IJCV*1e6;
IJCVSlow.time_ours = IJCVSlow.time_ours*1e6;
IJCVSlow.time_IJCV = IJCVSlow.time_IJCV*1e6;
%%
fprintf('PPA & $\\mathbf{%.2f \\pm %.2f}$ & $%.2f \\pm %.2f$ & $%.2f\\times$ %s\n', ...
    mean(PPASlow.time_ours(:)), std(PPASlow.time_ours(:)), ...
    mean(PPASlow.time_IJCV(:)), std(PPASlow.time_IJCV(:)), ...
    mean(PPASlow.time_IJCV(:)) / mean(PPASlow.time_ours(:)), '\\');

fprintf('GMPC & $\\mathbf{%.2f \\pm %.2f}$ & $%.2f \\pm %.2f$ & $%.2f\\times$ %s\n', ...
    mean(IJCVSlow.time_ours(:)), std(IJCVSlow.time_ours(:)), ...
    mean(IJCVSlow.time_IJCV(:)), std(IJCVSlow.time_IJCV(:)), ...
    mean(IJCVSlow.time_IJCV(:)) / mean(IJCVSlow.time_ours(:)), '\\');





